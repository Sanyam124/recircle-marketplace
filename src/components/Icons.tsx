/**
 * A helper function used by the landing page CategoryGrid.
 * Renders the correct icon component for a given icon name string.
 */
export function getIcon(name: string, className = 'w-8 h-8') {
    switch (name) {
        case 'book-open':        return <BookOpenIcon className={className} />;
        case 'document-text':    return <DocumentTextIcon className={className} />;
        case 'computer-desktop': return <ComputerDesktopIcon className={className} />;
        case 'home':             return <HomeIcon className={className} />;
        case 'shopping-bag':     return <ShoppingBagIcon className={className} />;
        case 'queue-list':       return <QueueListIcon className={className} />;
        case 'academic-cap':     return <AcademicCapIcon className={className} />;
        case 'paint-brush':      return <PaintBrushIcon className={className} />;
        case 'camera':           return <CameraIcon className={className} />;
        case 'sparkles':         return <SparklesIcon className={className} />;
        default:                 return null;
    }
}
